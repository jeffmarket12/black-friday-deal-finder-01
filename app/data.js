export function computeDealMetrics(deal) {
  const save = Math.max(0, deal.was - deal.price);
  const percent = deal.was > 0 ? Math.round((save / deal.was) * 100) : 0;
  return { ...deal, save, percent };
}

export function getAllDeals() {
  return dealsData.map(computeDealMetrics);
}
